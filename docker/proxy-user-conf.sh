#!/bin/sh
# --------------------------------------------------------------------------
# Who signed in at the identity provider in front, as nginx may believe it.
#
# A forward-auth proxy (Authelia, Authentik, oauth2-proxy for Keycloak) names
# the user it signed in in a header: SAMADCON_PROXY_USER_HEADER says which.
# nginx hands it to the application as X-Samadcon-Idp-User, and only for a
# request that came from a proxy in SAMADCON_TRUSTED_PROXIES. The hop is read
# from $realip_remote_addr, the address that actually connected, before
# real_ip replaced it with the browser's.
#
# From anyone else, and with nothing configured, the value is empty, and
# nginx.conf.template sets the header unconditionally: an empty value drops
# it, so whatever a browser sends as X-Samadcon-Idp-User never gets through.
#
# Writes to stdout; the entrypoint puts it next to real-ip.conf. Both values
# end up in nginx's configuration as written, so anything that is not a header
# name or an address is refused here, before nginx ever reads it.
# --------------------------------------------------------------------------
set -eu

# Trimmed at the ends only, as the application trims it: a space inside is
# not a header name, and is refused below rather than squeezed out.
header="$(printf '%s' "${SAMADCON_PROXY_USER_HEADER:-}" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
proxies="$(printf '%s' "${SAMADCON_TRUSTED_PROXIES:-}" | tr ',' ' ')"

case "${header}" in
    *[!A-Za-z0-9-]*)
        echo "SAMADCON_PROXY_USER_HEADER must be a header name: letters, digits and dashes." >&2
        exit 1
        ;;
esac
for proxy in ${proxies}; do
    case "${proxy}" in
        *[!0-9A-Fa-f.:/]*)
            echo "SAMADCON_TRUSTED_PROXIES: ${proxy} is not an address or a network." >&2
            exit 1
            ;;
    esac
done

echo "# Generated by proxy-user-conf.sh from SAMADCON_PROXY_USER_HEADER and"
echo "# SAMADCON_TRUSTED_PROXIES."
echo "geo \$realip_remote_addr \$samadcon_trusted_hop {"
echo "    default 0;"
if [ -n "${header}" ]; then
    for proxy in ${proxies}; do
        echo "    ${proxy} 1;"
    done
fi
echo "}"
echo "map \$samadcon_trusted_hop \$samadcon_idp_user {"
echo "    default \"\";"
if [ -n "${header}" ] && [ -n "${proxies}" ]; then
    # nginx's name for a request header: lower case, dashes as underscores.
    variable="$(printf '%s' "${header}" | tr 'A-Z-' 'a-z_')"
    echo "    1 \$http_${variable};"
fi
echo "}"
